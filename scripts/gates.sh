#!/bin/sh
# Regenerate docs/PROGRESS.md by running every gate.
#
# The gate table in PROGRESS.md is evidence, not prose: it must be produced by
# this script on the current tree, never copied from an earlier revision.
set -eu

cd "$(dirname "$0")/.."
OUT=docs/PROGRESS.md
GO=${GO:-go}

command -v "$GO" >/dev/null 2>&1 || { echo "no go toolchain on PATH" >&2; exit 1; }

gates="gate-m0 gate-m1 gate-m2 gate-m3 gate-m4 gate-m5 gate-m6 gate-m7 gate-m8"
fail=0

{
	printf '# Gate evidence\n\n'
	printf 'Generated by `scripts/gates.sh` at %s.\n\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
	printf 'Toolchain: %s\n\n' "$("$GO" version)"
	if command -v git >/dev/null 2>&1 && git rev-parse --verify HEAD >/dev/null 2>&1; then
		printf 'Revision: %s\n\n' "$(git rev-parse HEAD)"
	fi
	printf 'Each block below is raw output. A gate that fails is printed as it failed.\n\n'
} >"$OUT"

for g in $gates; do
	{
		printf '## %s\n\n' "$g"
		printf '```\n$ go run ./cmd/raftlab %s\n' "$g"
	} >>"$OUT"

	if timeout 1800 "$GO" run ./cmd/raftlab "$g" >>"$OUT" 2>&1; then
		:
	else
		fail=1
	fi
	printf '```\n\n' >>"$OUT"
done

{
	printf '## Supporting checks\n\n'
	printf '```\n$ go run ./cmd/importcheck\n'
} >>"$OUT"
"$GO" run ./cmd/importcheck >>"$OUT" 2>&1 || fail=1

{
	printf '$ go vet ./...\n'
} >>"$OUT"
"$GO" vet ./... >>"$OUT" 2>&1 || fail=1

{
	printf '$ go test ./...\n'
} >>"$OUT"
"$GO" test ./... >>"$OUT" 2>&1 || fail=1
printf '```\n\n' >>"$OUT"

if [ "$fail" -ne 0 ]; then
	printf 'Result: FAIL. Something above did not pass.\n' >>"$OUT"
	echo "gate evidence written to $OUT but not all checks passed" >&2
	exit 1
fi

printf 'Result: all gates and supporting checks passed.\n' >>"$OUT"
echo "gate evidence written to $OUT"
